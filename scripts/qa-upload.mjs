import { chromium } from "playwright";
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const errors = [];
const page = await browser.newPage({ viewport: { width: 1400, height: 860 } });
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
await page.goto("http://127.0.0.1:8080/", { waitUntil: "networkidle" });
await page.waitForSelector("h1", { timeout: 15000 });
await page.waitForTimeout(800);
await page.locator('input[type="file"]').first().setInputFiles("/tmp/sprint-test.mp4");
await page.waitForTimeout(2500);
const header = await page.locator("header").innerText();
const body = await page.locator("body").innerText();
await page.screenshot({ path: "/workspace/screenshots/lab-upload.png" });
await page.getByRole("button", { name: "Mills 评分" }).click();
await page.waitForTimeout(400);
await page.screenshot({ path: "/workspace/screenshots/lab-score.png" });
await page.getByRole("button", { name: "实时分析" }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: "/workspace/screenshots/lab-desktop.png" });
console.log(JSON.stringify({ errors, header: header.slice(0, 220), hasClip: body.includes("sprint-test") || body.includes("MP4") || /视频|播放|0:/.test(body) }, null, 2));
await browser.close();
